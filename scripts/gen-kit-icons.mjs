// Generates src/kit-icons.ts: the lucide icons the kit's own components render,
// so importing a component no longer pulls the whole collection. Run as part of
// the build; a new "lucide:..." literal in src is picked up automatically.
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { namesInDirs, subset } from "../src/iconSubset.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const out = resolve(here, "../src/kit-icons.ts")

const lucide = JSON.parse(readFileSync(require.resolve("@iconify-json/lucide/icons.json"), "utf8"))
const names = namesInDirs([resolve(here, "../src")])
const data = subset(lucide, names)
const missing = [...names].filter((n) => !data.icons[n] && !data.aliases?.[n])
if (missing.length) {
  console.error(`gen-kit-icons: unknown lucide icons: ${missing.join(", ")}`)
  process.exit(1)
}

const body = `/* AUTO-GENERATED by scripts/gen-kit-icons.mjs — do not edit.
 * The lucide icons kit components render, registered offline by icons.ts. */
import type { IconifyJSON } from "@iconify/vue"

export const KIT_ICONS: IconifyJSON = ${JSON.stringify(data)}
`

writeFileSync(out, body)
console.log(`gen-kit-icons: wrote ${Object.keys(data.icons).length} icons`)
