const lucide = JSON.parse(readFileSync(require.resolve("@iconify-json/lucide/icons.json"), "utf8"))
const pixel = JSON.parse(readFileSync(require.resolve("@iconify-json/pixelarticons/icons.json"), "utf8"))
const has = (set, name) => Boolean(set.icons[name] || set.aliases?.[name])

const map = {}
for (const name of [...Object.keys(lucide.icons), ...Object.keys(lucide.aliases ?? {})].sort()) {
  const target = SYNONYMS[name] ?? name
  if (has(pixel, target)) map[name] = target
}
const unknown = Object.entries(SYNONYMS).filter(([, target]) => !has(pixel, target))
if (unknown.length) {
  console.error(`gen-pixel-look: synonyms point at missing pixelarticons: ${unknown.map(([k, v]) => `${k}→${v}`).join(", ")}`)
  process.exit(1)
}

const data = subset(pixel, new Set(Object.values(map)))
writeFileSync(
  resolve(here, "../src/looks/pixel-icons.ts"),
  `/* AUTO-GENERATED by scripts/gen-pixel-look.mjs — do not edit.
 * lucide name → pixelarticons name, and the pixelarticons icons they need. */
import type { IconifyJSON } from "@iconify/vue"

export const PIXEL_ICON_MAP: Record<string, string> = ${JSON.stringify(map)}

export const PIXEL_ICONS: IconifyJSON = ${JSON.stringify(data)}
`,
)
console.log(`gen-pixel-look: ${Object.keys(map).length} lucide names mapped to ${Object.keys(data.icons).length} pixel icons`)
