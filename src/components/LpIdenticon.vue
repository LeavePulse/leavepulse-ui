<script lang="ts">
// The consumer's `class` is merged into the root's own (below) rather than
// appended to it, so opt out of the automatic pass-through that would add it
// a second time, unmerged.
export default { inheritAttrs: false }
</script>

<script setup lang="ts">
/*
 * A face for something that has no picture: a mirrored pixel pattern and a
 * colour, both derived from `seed` (an id, a username, a key's fingerprint).
 * The same seed draws the same identicon everywhere, so people learn to
 * recognise it the way they recognise an avatar.
 *
 * It fills the box it is put in (an LpAvatar sizes it through `identicon`);
 * give it a size class of its own anywhere else. The pattern is generated by
 * `identicon()` in identicon.ts, which a canvas, a favicon or a notification
 * icon can call directly.
 */
import { computed } from "vue"
import { identicon, identiconRects } from "./identicon"
import { useMergedAttrs } from "../composables/useMergedClass"

const props = withDefaults(
  defineProps<{
    /** What the picture is derived from. Use something stable: an id outlives a renamed username. */
    seed: string
    /** Cells per side: 5 is the familiar look, 7 gives busier shapes for large sizes. */
    grid?: number
    /**
     * `tint` lays a pale wash of the shape's own hue behind it, mixed into the
     * theme's soft surface so it sits right on dark and light alike; `none`
     * leaves the box behind it showing.
     */
    background?: "tint" | "none"
    /** Empty margin around the grid as a share of the side; more for a round crop. */
    padding?: number
    /** Accessible name. Unset, the picture is decorative: the name is usually written next to it. */
    label?: string
  }>(),
  { grid: 5, background: "tint", padding: 0.14 },
)

const icon = computed(() => identicon(props.seed, { grid: props.grid }))
const rects = computed(() => identiconRects(icon.value.cells))
const pad = computed(() => props.grid * Math.max(0, Math.min(0.4, props.padding)))
const view = computed(() => props.grid + pad.value * 2)
const wash = computed(() => `color-mix(in oklab, ${icon.value.color} 16%, var(--color-surface-soft))`)

const { class: rootClass, attrs: rest } = useMergedAttrs("block size-full")
</script>

<template>
  <svg
    :class="rootClass"
    v-bind="rest"
    :viewBox="`0 0 ${view} ${view}`"
    shape-rendering="crispEdges"
    :role="label ? 'img' : undefined"
    :aria-label="label"
    :aria-hidden="label ? undefined : 'true'"
  >
    <rect v-if="background === 'tint'" :width="view" :height="view" :style="{ fill: wash }" class="transition-[fill] duration-medium motion-reduce:transition-none" />
    <!-- Keyed by seed: a new seed is a new face, faded in rather than snapped. -->
    <g :key="seed" :fill="icon.color" class="animate-[fade-in_var(--duration-medium)_ease] motion-reduce:animate-none">
      <rect v-for="(r, i) in rects" :key="i" :x="r.x + pad" :y="r.y + pad" :width="r.w" height="1" />
    </g>
  </svg>
</template>
